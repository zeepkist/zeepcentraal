struct NoStorage;

#[async_trait]
impl ObjectStorage for NoStorage {
    async fn upload(&self, _: &str, _: Vec<u8>, _: &str) -> Result<()> {
        bail!("Unexpected upload")
    }
    async fn download(&self, _: &str, _: DownloadConstraints<'_>) -> Result<Vec<u8>> {
        bail!("Unexpected download")
    }
    async fn delete(&self, _: &str) -> Result<()> {
        bail!("Unexpected deletion")
    }
}

async fn post(app: &Router, credential: Option<(&str, bool)>, body: Value) -> Result<StatusCode> {
    let mut request =
        Request::post("/level/request").header(header::CONTENT_TYPE, "application/json");
    if let Some((token, bearer)) = credential {
        request = if bearer {
            request.header(header::AUTHORIZATION, format!("Bearer {token}"))
        } else {
            request.header(header::COOKIE, format!("{ACCESS_TOKEN}={token}"))
        };
    }
    let response = app
        .clone()
        .oneshot(request.body(Body::from(body.to_string()))?)
        .await?;
    let status = response.status();
    if status == StatusCode::OK {
        assert!(to_bytes(response.into_body(), 4096).await?.is_empty());
    }
    Ok(status)
}

#[tokio::test]
#[ignore = "requires an empty local workshop_scan_http_test database with pgmq 1.12.0"]
async fn web_and_gtr_share_the_workshop_scan_cooldown() -> Result<()> {
    let url = std::env::var("ZC_TEST_DATABASE_URL")?;
    let parsed = url::Url::parse(&url)?;
    ensure!(parsed.host_str() == Some("127.0.0.1") && parsed.path() == "/workshop_scan_http_test");
    let (client, connection) = tokio_postgres::connect(&url, tokio_postgres::NoTls).await?;
    let connection = tokio::spawn(connection);
    for sql in [
        include_str!("../../database/tests/fixtures/zsl_tournament.sql"),
        include_str!("../../../packages/database/drizzle/0083_pgmq_queue.sql"),
        include_str!("../../database/migrations/20261116010000_queue_trace_context/up.sql"),
        include_str!("../../database/migrations/20261124000000_workshop_scan_requests/up.sql"),
        r#"CREATE TABLE public.level_request (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            workshop_id bigint UNIQUE NOT NULL,
            hash text
        );
        INSERT INTO public."user" (steam_id, steam_name) VALUES (42, 'Fixture');
        INSERT INTO public.level (hash, xx_hash) VALUES ('existing', repeat('B', 32));"#,
    ] {
        client.batch_execute(sql).await?;
    }

    let state = support::state(&url, Arc::new(NoStorage), false)?;
    let app = zc_server::app::router(state.clone())?;
    let steam = state
        .config
        .jwt
        .issue(Provider::Steam, "42", None)?
        .access_token;
    let discord = state
        .config
        .jwt
        .issue(Provider::Discord, "42", Some("123"))?
        .access_token;
    let gtr = state
        .config
        .jwt
        .issue(Provider::Gtr, "42", None)?
        .access_token;
    let web = |id: i64| json!({"workshopId":id.to_string()});
    let legacy = |id: i64| json!({"WorkshopId":id.to_string(),"Hash":"A".repeat(32)});
    assert_eq!(post(&app, None, web(100)).await?, StatusCode::UNAUTHORIZED);
    assert_eq!(
        post(&app, Some((&gtr, true)), web(100)).await?,
        StatusCode::UNAUTHORIZED
    );
    assert_eq!(
        post(&app, Some((&steam, false)), legacy(100)).await?,
        StatusCode::UNAUTHORIZED
    );
    assert_eq!(
        post(&app, Some((&steam, false)), web(0)).await?,
        StatusCode::BAD_REQUEST
    );
    assert_eq!(
        post(
            &app,
            Some((&gtr, true)),
            json!({"WorkshopId":"100","Hash":"B".repeat(32)})
        )
        .await?,
        StatusCode::OK
    );
    assert!(state.queue.claim(JobLane::Bulk, 1).await?.is_empty());

    let (left, right) = tokio::join!(
        post(&app, Some((&steam, false)), web(100)),
        post(&app, Some((&discord, false)), web(100)),
    );
    assert_eq!(left?, StatusCode::OK);
    assert_eq!(right?, StatusCode::OK);
    let jobs = state.queue.claim(JobLane::Bulk, 2).await?;
    assert_eq!(jobs.len(), 1);
    assert_eq!(
        jobs[0].payload,
        json!({"workshopId":"100","checkForUpdates":true})
    );
    client.execute("UPDATE zc_private.workshop_scan_request SET last_requested_at = now() - interval '15 minutes' WHERE workshop_id = 100", &[]).await?;
    assert_eq!(
        post(&app, Some((&gtr, true)), legacy(100)).await?,
        StatusCode::OK
    );
    assert!(
        state.queue.claim(JobLane::Bulk, 1).await?.is_empty(),
        "a running scan coalesces"
    );
    assert!(state.queue.finish(&jobs[0], None).await?);
    assert_eq!(
        post(&app, Some((&gtr, false)), legacy(100)).await?,
        StatusCode::OK
    );
    let jobs = state.queue.claim(JobLane::Bulk, 2).await?;
    assert_eq!(jobs.len(), 1);
    assert_eq!(jobs[0].payload, json!({"workshopId":"100"}));
    state.database.release_level_request(100).await?;
    assert!(state.queue.finish(&jobs[0], None).await?);
    assert_eq!(
        post(&app, Some((&discord, false)), web(100)).await?,
        StatusCode::OK
    );
    assert!(
        state.queue.claim(JobLane::Bulk, 1).await?.is_empty(),
        "GTR cooldown applies to web"
    );

    assert_eq!(
        post(&app, Some((&steam, false)), web(101)).await?,
        StatusCode::OK
    );
    let jobs = state.queue.claim(JobLane::Bulk, 2).await?;
    assert_eq!(jobs.len(), 1);
    assert!(state.queue.finish(&jobs[0], None).await?);
    assert_eq!(
        post(&app, Some((&gtr, true)), legacy(101)).await?,
        StatusCode::OK
    );
    assert!(
        state.queue.claim(JobLane::Bulk, 1).await?.is_empty(),
        "web cooldown applies to GTR"
    );

    state
        .queue
        .enqueue(
            TaskIdentifier::ScanWorkshopBatch,
            json!({"workshopIds":["103","104"]}),
            JobLane::Bulk,
            Some("fixture-workshop-batch"),
        )
        .await?;
    assert_eq!(
        post(&app, Some((&steam, false)), web(104)).await?,
        StatusCode::OK
    );
    let jobs = state.queue.claim(JobLane::Bulk, 2).await?;
    assert_eq!(jobs.len(), 1, "request coalesces with a scheduled batch");
    assert_eq!(jobs[0].task, TaskIdentifier::ScanWorkshopBatch.as_str());
    assert!(state.queue.finish(&jobs[0], None).await?);

    client
        .batch_execute("ALTER TABLE zc_jobs.job ADD CHECK (job_key <> 'refresh-workshop-item:102')")
        .await?;
    assert_eq!(
        post(&app, Some((&steam, false)), web(102)).await?,
        StatusCode::INTERNAL_SERVER_ERROR
    );
    assert!(!client.query_one("SELECT EXISTS (SELECT 1 FROM zc_private.workshop_scan_request WHERE workshop_id = 102)", &[]).await?.get::<_, bool>(0));
    drop(client);
    connection.await??;
    Ok(())
}
